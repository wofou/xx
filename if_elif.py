# 定义一个变量 score，存放分数
score = 88

# 如果分数大于等于90，执行这里
if score >= 90:
    print("优秀")  # 输出：优秀

# 否则如果分数大于等于60，执行这里
elif score >= 60:
    print("及格")  # 输出：及格

# 上面条件都不满足，执行这里
else:
    print("不及格")  # 输出：不及格

#==  等于 （注意是两个等号！）
#!=  不等于
#>   大于
#<   小于
#>=  大于等于
#<=  小于等于

age = 20                  # 定义年龄变量
# 满足 age>=18 取"成年"，否则取"未成年"
res = "成年" if age >= 18 else "未成年"
print(res)                # 打印结果