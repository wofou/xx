# 加法 +
print(5 + 3)   # 结果是 8

# 减法 -
print(5 - 3)   # 结果是 2

# 乘法 * (用的是星号，不是 x)
print(5 * 3)   # 结果是 15

# 除法 / (结果是浮点数)
print(10 / 4)  # 结果是 2.5

print(10 // 4)  # 结果是 2 (因为 10 除以 4 是 2.5，直接舍去 .5)

print(10 % 4)  # 结果是 2 (因为 10 除以 4 得 2 余 2)

#混合运算会变成浮点数
print(5 + 3)      # 全是整数，结果是整数 8
print(5 + 3.0)    # 3.0 是浮点数，结果就是浮点数 8.0

# 除法 / 特别容易产生浮点数
print(10 / 2)     # 结果是 5.0，而不是整数 5

print(0.1 + 0.2)  
# 你期望的结果是 0.3
# 但 Python 可能会输出：0.30000000000000004